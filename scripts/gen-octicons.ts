// Regenerates src/view/octicons.ts from @primer/octicons (MIT).
// Run with: pnpm gen:octicons
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const ICONS = [
  "alert",
  "arrow-switch",
  "check",
  "check-circle-fill",
  "chevron-down",
  "chevron-right",
  "circle",
  "clock",
  "dash",
  "focus-center",
  "fold",
  "git-merge",
  "graph",
  "hourglass",
  "iterations",
  "kebab-horizontal",
  "plus",
  "screen-full",
  "screen-normal",
  "search",
  "skip",
  "stop",
  "unfold",
  "workflow",
  "x",
  "x-circle-fill",
  "zap",
] as const;

const require = createRequire(import.meta.url);
const dataPath = require.resolve("@primer/octicons/build/data.json");
const data = JSON.parse(readFileSync(dataPath, "utf8")) as Record<
  string,
  { heights: Record<string, { path: string }> }
>;

const entries = ICONS.map((name) => {
  const icon = data[name];
  if (!icon?.heights["16"]) throw new Error(`Missing 16px octicon: ${name}`);
  const paths = [...icon.heights["16"].path.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  return `  "${name}": ${JSON.stringify(paths)},`;
});

const out = `// Generated by scripts/gen-octicons.ts from @primer/octicons (MIT). Do not edit.
export const OCTICONS = {
${entries.join("\n")}
} as const satisfies Record<string, readonly string[]>;

export type OcticonName = keyof typeof OCTICONS;
`;

writeFileSync(new URL("../src/view/octicons.ts", import.meta.url), out);
console.log(`Wrote ${ICONS.length} icons.`);
